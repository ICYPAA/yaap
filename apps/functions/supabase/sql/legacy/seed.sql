-- Reset tables if they exist
DROP TABLE IF EXISTS registrations;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS inquiries;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS reminders;
DROP TABLE IF EXISTS volunteering;
DROP TABLE IF EXISTS reports;
DROP TABLE IF EXISTS volunteering_interest;

-- Create users table
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    email TEXT UNIQUE NOT NULL,
    first_name TEXT,
    last_name TEXT,
    phone TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create events table
CREATE TABLE events (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    title TEXT NOT NULL CHECK (LENGTH(title) >= 2),
    description TEXT NOT NULL CHECK (LENGTH(description) >= 10),
    date DATE NOT NULL,
    time TIME NOT NULL,
    location TEXT NOT NULL CHECK (LENGTH(location) >= 2),
    image_url TEXT NOT NULL,
    is_icypaa_event BOOLEAN DEFAULT false,
    created_by UUID REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create registrations table
CREATE TABLE registrations (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES users(id),
    registration_number TEXT UNIQUE NOT NULL,
    submitted_by UUID REFERENCES users(id),
    submitted_on TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create inquiries table
CREATE TABLE inquiries (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    inquiry_type TEXT NOT NULL CHECK (inquiry_type IN ('registration', 'program', 'hotel', 'other')),
    message TEXT NOT NULL,
    status TEXT DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'closed')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create the reminders table
CREATE TABLE reminders (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    type TEXT UNIQUE NOT NULL,
    time TEXT NOT NULL,
    place TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create the volunteering_interest table for both general interest and marathon meetings
CREATE TABLE volunteering_interest (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    last_initial TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('general', 'marathon')),
    data JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Create the volunteering table with JSONB for the jobs structure
CREATE TABLE volunteering (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    jobs JSON NOT NULL DEFAULT '[]'::JSON,

    CONSTRAINT jobs_structure CHECK (
        JSON_TYPEOF(jobs) = 'array'
        AND (
            SELECT BOOL_AND(
                job->>'name' IS NOT NULL
                AND JSON_TYPEOF(job->'time_slots') = 'array'
                AND (
                    SELECT BOOL_AND(
                        slot->>'time' IS NOT NULL
                        AND (slot->>'max_volunteers')::INT IS NOT NULL
                        AND JSON_TYPEOF(slot->'current_volunteers') = 'array'
                    )
                    FROM JSON_ARRAY_ELEMENTS(job->'time_slots') slot
                )
            )
            FROM JSON_ARRAY_ELEMENTS(jobs) job
        )
    )
);

-- Create reports table
CREATE TABLE reports (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES auth.users(id) NOT NULL,
    team TEXT NOT NULL CHECK (team IN ('MAIN_MEETING', 'HOST_TEAM_1', 'HOST_TEAM_2', 'HOST_TEAM_3')),
    chair_position TEXT NOT NULL,
    current_work TEXT NOT NULL,
    needs_help TEXT NOT NULL,
    team_meeting_items TEXT NOT NULL,
    agenda_doc_id TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

