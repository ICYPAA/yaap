-- Create policies
-- Users can read all public data
CREATE POLICY "Users can view all events" ON events FOR SELECT USING (true);
CREATE POLICY "Users can view all inquiries" ON inquiries FOR SELECT USING (true);

-- Only authenticated users can create events
CREATE POLICY "Authenticated users can create events" ON events
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Only admins can manage registrations
CREATE POLICY "Admins can manage registrations" ON registrations
    USING (auth.role() = 'authenticated' AND EXISTS (
        SELECT 1 FROM users
        WHERE users.id = auth.uid()
        AND email LIKE '%@icypaa.org'
    ));

-- Users can create inquiries
CREATE POLICY "Anyone can create inquiries" ON inquiries
    FOR INSERT WITH CHECK (true);

-- Enable read access for authenticated users
CREATE POLICY "Enable read access for authenticated users" ON reminders FOR SELECT USING (auth.role() = 'authenticated');

-- Enable write access for authenticated users
CREATE POLICY "Enable write access for authenticated users" ON reminders FOR ALL USING (auth.role() = 'authenticated');

-- Enable full access for authenticated users on reminders
CREATE POLICY "Authenticated users can perform all actions on reminders" ON reminders
    FOR ALL USING (auth.role() = 'authenticated');

-- Enable read access for all users
CREATE POLICY "Enable read access for all users" ON volunteering FOR SELECT USING (true);

-- Enable insert/update for authenticated users
CREATE POLICY "Enable insert/update for authenticated users" ON volunteering FOR UPDATE USING (auth.role() = 'authenticated');

-- Policy to allow authenticated users to create reports
CREATE POLICY "Authenticated users can create reports" ON reports
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Policy to allow users to view their own reports
CREATE POLICY "Users can view their own reports" ON reports
    FOR SELECT USING (auth.uid() = user_id);

-- Policies for volunteering_interest
CREATE POLICY "Anyone can submit volunteering interest" ON volunteering_interest
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Authenticated users can view volunteering interest" ON volunteering_interest
    FOR SELECT USING (auth.role() = 'authenticated');
